    expect(cells).to_have_count(90)
    cells.first.focus();page.keyboard.press('ArrowRight')
    expect(cells.nth(7)).to_be_focused()
    expect(page.locator('.an-calendar-detail')).to_have_text(cells.nth(7).get_attribute('aria-label'))
    page.keyboard.press('End');expect(cells.last).to_be_focused()
    expect(page.locator('.an-calendar-detail')).to_contain_text('Today so far')
    assert cells.evaluate_all('(els) => els.every(el => { const r = el.getBoundingClientRect(); return Math.abs(r.width - r.height) < 1; })'), 'Calendar cells must be square'
    assert cells.evaluate_all('(els) => els.some(el => el.dataset.level === "0") && els.some(el => el.dataset.level === "4")'), 'Calendar must distinguish zero and peak activity'
    page.locator('.an-calendar').screenshot(path=str(captures/'cms-activity-calendar-desktop.png'))
