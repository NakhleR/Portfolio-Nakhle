    assert page.evaluate('history.state.page instanceof ArrayBuffer'), 'Private page history should be encrypted'
    page.get_by_role('link',name='Pages & content',exact=True).click()
    expect(page.get_by_role('heading',name='Homepage',exact=True)).to_be_visible()
    expect(page.locator('html')).to_have_class('dark')
    expect(page.get_by_label('Helix caption',exact=True)).to_have_css('background-color','rgb(255, 255, 255)')
    expect(page.get_by_label('Helix caption',exact=True)).to_have_css('color','rgb(32, 37, 30)')
