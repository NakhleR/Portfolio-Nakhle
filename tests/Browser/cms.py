    with page.expect_popup() as popup:
        page.get_by_role('link',name='Preview saved draft').click()
    preview=popup.value;preview.wait_for_load_state();expect(preview.locator('h1')).to_have_text('Browser tested heading');preview.close()
    page.once('dialog',lambda dialog:dialog.accept())
    page.get_by_role('button',name='Publish',exact=True).click()
    expect(page.get_by_role('status')).to_contain_text('Published.')
    visitor.reload();expect(visitor.locator('h1')).to_have_text('Browser tested heading');visitor.close()
    page.screenshot(path=str(captures/'cms-editor-desktop.png'),full_page=True)
    page.locator('#cms-section').select_option('about');expect(page.get_by_role('heading',name='About & skills',exact=True)).to_be_visible()
